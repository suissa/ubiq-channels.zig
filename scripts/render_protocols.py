#!/usr/bin/env python3
"""Render deploy/Caddyfile from the deliberately small configs/protocols.yml schema.

Only flat scalar YAML is accepted so generation has no third-party dependencies.
Run normally to update the Caddyfile, or pass --check in CI to detect drift.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "configs" / "protocols.yml"
OUTPUT = ROOT / "deploy" / "Caddyfile"

DEFAULTS = {
    "http1": "true",
    "http2": "true",
    "http3": "true",
    "grpc": "true",
    "tls_mode": "internal",
    "https_host": "localhost",
    "https_port": "8443",
    "http_host": "localhost",
    "http_port": "8081",
    "backend_host": "127.0.0.1",
    "backend_port": "8080",
    "grpc_host": "127.0.0.1",
    "grpc_port": "9090",
}


def parse_config(path: Path) -> dict[str, str]:
    values = DEFAULTS.copy()
    for line_number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if ":" not in line:
            raise ValueError(f"{path}:{line_number}: expected key: value")
        key, value = (part.strip() for part in line.split(":", 1))
        if key not in DEFAULTS:
            raise ValueError(f"{path}:{line_number}: unknown key {key!r}")
        if not value:
            raise ValueError(f"{path}:{line_number}: missing value for {key}")
        values[key] = value.strip("\"'")
    for key in ("http1", "http2", "http3", "grpc"):
        if values[key].lower() not in ("true", "false"):
            raise ValueError(f"{key} must be true or false")
        values[key] = values[key].lower()
    if not any(values[key] == "true" for key in ("http1", "http2", "http3", "grpc")):
        raise ValueError("at least one of http1, http2, http3, or grpc must be enabled")
    if values["http2"] == "true" and values["http1"] != "true":
        raise ValueError("Caddy requires HTTP/1.1 enabled when HTTP/2 is enabled")
    if values["http3"] == "true" and values["tls_mode"] not in ("internal", "managed"):
        raise ValueError("HTTP/3 requires tls_mode: internal or managed")
    if values["tls_mode"] not in ("internal", "managed"):
        raise ValueError("tls_mode must be internal or managed")
    for key in ("https_port", "http_port", "backend_port", "grpc_port"):
        try:
            port = int(values[key])
        except ValueError as exc:
            raise ValueError(f"{key} must be an integer port") from exc
        if not 1 <= port <= 65535:
            raise ValueError(f"{key} must be between 1 and 65535")
    for key in ("https_host", "http_host", "backend_host", "grpc_host"):
        if any(ch.isspace() for ch in values[key]) or not values[key]:
            raise ValueError(f"{key} must be a non-empty hostname or IP without whitespace")
    return values


def render(values: dict[str, str]) -> str:
    protocols = " ".join(
        protocol for key, protocol in (("http1", "h1"), ("http2", "h2"), ("http3", "h3"))
        if values[key] == "true"
    )
    tls_directive = "    tls internal\n" if values["tls_mode"] == "internal" else ""
    https_site = ""
    if values["http2"] == "true" or values["http3"] == "true" or values["tls_mode"] in ("internal", "managed"):
        if values["grpc"] == "true":
            https_handlers = (
                f"    @grpc path /ubiq.channels.v1.ChannelService/*\n"
                "    handle @grpc {\n"
                f"        reverse_proxy h2c://{values['grpc_host']}:{values['grpc_port']}\n"
                "    }\n"
                "    handle {\n"
                f"        reverse_proxy {values['backend_host']}:{values['backend_port']} {{\n"
                "            # Flush each upstream write so SSE is streamed instead of buffered.\n"
                "            flush_interval -1\n"
                "        }\n"
                "    }\n"
            )
        else:
            https_handlers = (
                f"    reverse_proxy {values['backend_host']}:{values['backend_port']} {{\n"
                "        # Flush each upstream write so SSE is streamed instead of buffered.\n"
                "        flush_interval -1\n"
                "    }\n"
            )
        https_site = (
            f"https://{values['https_host']}:{values['https_port']} {{\n"
            f"{tls_directive}"
            f"{https_handlers}"
            "}\n"
        )
    http_site = (
        f"http://{values['http_host']}:{values['http_port']} {{\n"
        f"    reverse_proxy {values['backend_host']}:{values['backend_port']} {{\n"
        "        flush_interval -1\n"
        "    }\n"
        "}\n"
    ) if values["http1"] == "true" else ""
    return (
        "# Generated by scripts/render_protocols.py from configs/protocols.yml. Do not edit manually.\n"
        "# HTTP/2 and HTTP/3 terminate at Caddy; the Zig upstream speaks HTTP/1.1.\n"
        "{\n"
        "    servers {\n"
        f"        protocols {protocols}\n"
        "    }\n"
        "}\n\n"
        + https_site + "\n" + http_site
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if deploy/Caddyfile is not up to date")
    args = parser.parse_args()
    try:
        expected = render(parse_config(CONFIG))
    except (OSError, ValueError) as exc:
        print(f"protocol config error: {exc}", file=sys.stderr)
        return 2
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run python3 scripts/render_protocols.py", file=sys.stderr)
            return 1
        print("protocol config and Caddyfile are in sync")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"generated {OUTPUT.relative_to(ROOT)} from {CONFIG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
